#region "Usings"

using System.Collections.Immutable;
using System.Text;
using Istarnova.SourceGenerator.Common;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace Istarnova.SourceGenerator.Data.Equatable;

/// <summary>
///     Incremental source generator that generates IEquatable implementation for classes marked with
///     AutoEquatableAttribute.
/// </summary>
[Generator]
public class AutoEquatableGenerator : IIncrementalGenerator
{
    #region "Constants"

    private const string AutoEquatableAttributeFullName =
        "Istarnova.SourceGenerator.Attributes.Data.Equatable.AutoEquatableAttribute";

    #endregion

    #region "Methods"

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classDeclarations = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AutoEquatableAttributeFullName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => GetClassInfo(ctx))
            .Where(static info => info is { });

        context.RegisterSourceOutput(classDeclarations, static (spc, classInfo) =>
        {
            if (classInfo is null)
            {
                return;
            }

            var info = classInfo.Value;

            // Check if class is partial
            if (!info.IsPartial)
            {
                ReportDiagnostic(spc, info, "AE001", "Class must be partial",
                    $"Class '{info.ClassName}' must be declared as partial to use AutoEquatable.");
                return;
            }

            // Check for key properties
            if (info.KeyProperties.Length == 0)
            {
                ReportDiagnostic(spc, info, "AE002", "No key properties found",
                    $"No key properties found for class '{info.ClassName}'. " +
                    $"Expected property '{info.ClassName}Id' or specify KeyProperties explicitly.");
                return;
            }

            var sourceCode = GenerateEquatableImplementation(info);
            spc.AddSource($"{info.ClassName}_Equatable.g.cs", sourceCode);
        });
    }

    private static PropertyInfo CreatePropertyInfo(IPropertySymbol property)
    {
        var type = property.Type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable
            ? nullable.TypeArguments[0]
            : property.Type;

        var isGeneratedKeyType = type.SpecialType is >= SpecialType.System_SByte and <= SpecialType.System_UInt64
                                 || type.ToDisplayString() == "System.Guid";

        return new(property.Name, property.Type.IsReferenceType, isGeneratedKeyType);
    }

    private static string GenerateEqualsComparison(ImmutableArray<PropertyInfo> keyProperties)
    {
        if (keyProperties.Length == 1)
        {
            var prop = keyProperties[0];

            return prop.IsReferenceType
                ? $"Equals({prop.Name}, other.{prop.Name})"
                : $"{prop.Name} == other.{prop.Name}";
        }

        var comparisons = keyProperties.Select(prop =>
            prop.IsReferenceType
                ? $"Equals({prop.Name}, other.{prop.Name})"
                : $"{prop.Name} == other.{prop.Name}");

        return string.Join(" && ", comparisons);
    }

    private static string GenerateEquatableImplementation(ClassInfo classInfo)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine(GeneratedNamespace.Declaration(classInfo.Namespace));
        sb.AppendLine();

        sb.AppendLine($"public partial class {classInfo.ClassName} : IEquatable<{classInfo.ClassName}>");
        sb.AppendLine("{");

        // Equals(T? other)
        sb.AppendLine($"    public bool Equals({classInfo.ClassName}? other)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (other is null)");
        sb.AppendLine("        {");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        if (ReferenceEquals(this, other))");
        sb.AppendLine("        {");
        sb.AppendLine("            return true;");
        sb.AppendLine("        }");
        sb.AppendLine();

        var unsavedCheck = GenerateUnsavedCheck(classInfo.KeyProperties);

        if (unsavedCheck is { })
        {
            sb.AppendLine($"        if ({unsavedCheck})");
            sb.AppendLine("        {");
            sb.AppendLine("            return false;");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        sb.AppendLine($"        return {GenerateEqualsComparison(classInfo.KeyProperties)};");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Equals(object? obj)
        sb.AppendLine("    public override bool Equals(object? obj)");
        sb.AppendLine($"        => Equals(obj as {classInfo.ClassName});");
        sb.AppendLine();

        // GetHashCode()
        sb.AppendLine("    public override int GetHashCode()");
        sb.AppendLine($"        => {GenerateHashCode(classInfo.KeyProperties)};");

        // Operators
        if (classInfo.GenerateOperators)
        {
            sb.AppendLine();
            sb.AppendLine(
                $"    public static bool operator ==({classInfo.ClassName}? left, {classInfo.ClassName}? right)");
            sb.AppendLine("        => Equals(left, right);");
            sb.AppendLine();
            sb.AppendLine(
                $"    public static bool operator !=({classInfo.ClassName}? left, {classInfo.ClassName}? right)");
            sb.AppendLine("        => !Equals(left, right);");
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string GenerateHashCode(ImmutableArray<PropertyInfo> keyProperties)
    {
        if (keyProperties.Length == 1)
        {
            var prop = keyProperties[0];

            return prop.IsReferenceType
                ? $"{prop.Name}?.GetHashCode() ?? 0"
                : $"{prop.Name}.GetHashCode()";
        }

        var propNames = string.Join(", ", keyProperties.Select(p => p.Name));

        return $"HashCode.Combine({propNames})";
    }

    /// <summary>
    ///     The condition under which this object has not been saved yet, or null when its key cannot tell.
    /// </summary>
    /// <returns>
    ///     A numeric or Guid key still at its default was never assigned by the database, so two such objects
    ///     are two new things rather than one; only reference equality may hold for them. A string or enum key
    ///     yields null, because its default is a valid stored key.
    /// </returns>
    private static string? GenerateUnsavedCheck(ImmutableArray<PropertyInfo> keyProperties)
    {
        var generatedKeys = keyProperties.Where(prop => prop.IsGeneratedKeyType).ToList();

        return generatedKeys.Count == 0
            ? null
            : string.Join(" && ", generatedKeys.Select(prop => $"{prop.Name} == default"));
    }

    private static ClassInfo? GetClassInfo(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol classSymbol)
        {
            return null;
        }

        if (context.TargetNode is not ClassDeclarationSyntax classDeclaration)
        {
            return null;
        }

        var attribute = context.Attributes.FirstOrDefault();
        if (attribute is null)
        {
            return null;
        }

        var keyPropertiesArg = GetKeyPropertiesFromAttribute(attribute);
        var generateOperators = GetGenerateOperatorsFromAttribute(attribute);
        var isPartial = classDeclaration.Modifiers.Any(m => m.Text == "partial");

        var keyProperties = GetKeyProperties(classSymbol, keyPropertiesArg);

        return new ClassInfo(
            GeneratedNamespace.Of(classSymbol),
            classSymbol.Name,
            isPartial,
            generateOperators,
            keyProperties,
            classSymbol.Locations.FirstOrDefault());
    }

    private static bool GetGenerateOperatorsFromAttribute(AttributeData attribute)
    {
        foreach (var namedArg in attribute.NamedArguments)
        {
            if (namedArg is { Key: "GenerateOperators", Value.Value: bool value })
            {
                return value;
            }
        }

        return true;
    }

    private static ImmutableArray<PropertyInfo> GetKeyProperties(INamedTypeSymbol classSymbol, string? explicitKeys)
    {
        var properties = classSymbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => p.DeclaredAccessibility == Accessibility.Public && p.GetMethod is { })
            .ToList();

        if (!string.IsNullOrWhiteSpace(explicitKeys))
        {
            var keyNames = new HashSet<string>(explicitKeys!.Split(',').Select(k => k.Trim()));

            return
            [
                .. properties
                    .Where(p => keyNames.Contains(p.Name))
                    .Select(CreatePropertyInfo),
            ];
        }

        // Convention: {ClassName}Id
        var conventionKeyName = $"{classSymbol.Name}Id";
        var conventionKey = properties.FirstOrDefault(p => p.Name == conventionKeyName);

        return conventionKey is { }
            ? [CreatePropertyInfo(conventionKey)]
            : [];
    }

    private static string? GetKeyPropertiesFromAttribute(AttributeData attribute)
    {
        foreach (var namedArg in attribute.NamedArguments)
        {
            if (namedArg is { Key: "KeyProperties", Value.Value: string value })
            {
                return value;
            }
        }

        return null;
    }

    private static void ReportDiagnostic(
        SourceProductionContext context,
        ClassInfo classInfo,
        string id,
        string title,
        string message)
    {
        var diagnostic = Diagnostic.Create(
            new(
                id,
                title,
                message,
                "AutoEquatable",
                DiagnosticSeverity.Error,
                true),
            classInfo.Location);

        context.ReportDiagnostic(diagnostic);
    }

    #endregion

    private readonly record struct ClassInfo(
        string Namespace,
        string ClassName,
        bool IsPartial,
        bool GenerateOperators,
        ImmutableArray<PropertyInfo> KeyProperties,
        Location? Location);

    private readonly record struct PropertyInfo(
        string Name,
        bool IsReferenceType,
        bool IsGeneratedKeyType);
}
